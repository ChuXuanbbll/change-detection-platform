import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const output = process.env.BROWSER_OUTPUT_DIR || 'data/validation/management-ui';
await fs.mkdir(output, { recursive: true });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto((process.env.FRONTEND_URL || 'http://localhost:5173') + '/management');
  await page.getByText('已生效', { exact: false }).first().waitFor();
  await page.getByRole('tab', { name: '检测默认值' }).click();
  await page.getByLabel('变化概率阈值').fill('0.61');
  await page.getByRole('button', { name: '应用配置', exact: true }).click();
  await page.getByRole('button', { name: '应用配置', exact: true }).waitFor({ timeout: 120000 });
  assert.equal(await page.getByRole('alert').count(), 0, await page.locator('.management').innerText());
  const state = await page.request.get(new URL('/api/settings', page.url()).href).then(r => r.json());
  assert.equal(state.settings.detection.threshold, .61);
  assert.equal(state.effective, true);
  await page.screenshot({ path: path.join(output, 'defaults-desktop.png'), fullPage: true });
  await page.getByRole('tab', { name: '模型', exact: true }).click();
  await page.getByText('河北变化检测', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'models-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('tab', { name: '影像来源', exact: true }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.waitForTimeout(350);
  await page.screenshot({ path: path.join(output, 'sources-mobile.png'), fullPage: true });
  await page.reload();
  await page.getByRole('tab', { name: '检测默认值' }).click();
  await page.getByLabel('变化概率阈值').waitFor();
  assert.equal(await page.getByLabel('变化概率阈值').inputValue(), '0.61');
  assert.deepEqual(errors, []);
  console.log('Management browser passed: persisted defaults, model list, mobile layout, reload');
} finally { await browser.close(); }
